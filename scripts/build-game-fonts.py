"""Build OFL webfonts from the official originals; requires fonttools[woff].

Usage: PYTHONPATH=.cache/menu-font-tools /usr/bin/python3 scripts/build-game-fonts.py
Originals live in .cache/menu-font-originals (see public/fonts/README.md).
All source cmap characters are retained across disjoint, demand-loaded shards.
"""
from pathlib import Path
import hashlib
import json
import re
import shutil
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / '.cache/menu-font-originals'
OUT = ROOT / 'public/fonts'
OUT.mkdir(parents=True, exist_ok=True)


def ranges(points):
    spans = []
    for cp in sorted(points):
        if spans and cp == spans[-1][1] + 1:
            spans[-1][1] = cp
        else:
            spans.append([cp, cp])
    return ','.join('U+%X' % a if a == b else 'U+%X-%X' % (a, b) for a, b in spans)


text = ''.join(p.read_text() for p in (ROOT / 'src').rglob('*') if p.suffix in ('.ts', '.tsx', '.json'))
common = set(range(0x20, 0x100)) | {ord(c) for c in re.findall(r'[\u3000-\u303f\u3400-\u9fff\uff00-\uffef]', text)}
common |= {ord(c) for c in '−·—“”‘’…风云南北朝'}
css = ['/* Generated by scripts/build-game-fonts.py. OFL licenses beside these files. */']
manifest = []
for file, stem, weight in [('source-serif-Regular.otf', 'song-regular', 400), ('source-serif-SemiBold.otf', 'song-semibold', 600), ('mashanzheng.ttf', 'title-ma', 400)]:
    original = SOURCE / file
    font = TTFont(original)
    cmap = set(font.getBestCmap())
    title = stem == 'title-ma'
    # The title family intentionally contains only the game's five title glyphs.
    primary = ({ord(c) for c in '风云南北朝'} if title else common) & cmap
    remaining = sorted(cmap - primary)
    groups = [('core', sorted(primary))]
    if not title:
        groups += [(str(i // 2048 + 1).zfill(2), remaining[i:i + 2048]) for i in range(0, len(remaining), 2048)]
    family = 'FYN Ma Title' if title else 'FYN Song'
    internal = 'FYNMaTitle' if title else 'FYNSong'
    style = 'SemiBold' if weight == 600 else 'Regular'
    for suffix, points in groups:
        current = TTFont(original)
        options = subset.Options()
        options.name_IDs = ['*']
        options.name_languages = ['*']
        options.name_legacy = True
        options.layout_features = ['*']
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=points)
        sub.subset(current)
        for name in current['name'].names:
            value = {1: internal, 2: style, 3: internal + '-' + style + '-' + suffix, 4: internal + ' ' + style, 6: internal + '-' + style, 16: internal, 17: style}.get(name.nameID)
            if value:
                name.string = value.encode(name.getEncoding())
        if 'CFF ' in current:
            cff = current['CFF '].cff
            cff.fontNames = [internal + '-' + style]
            cff.topDictIndex[0].FamilyName = internal
            cff.topDictIndex[0].FullName = internal + ' ' + style
        current.flavor = 'woff2'
        dest = OUT / (stem + '-' + suffix + '.woff2')
        current.save(dest)
        css.append("@font-face{font-family:'%s';font-style:normal;font-weight:%s;font-display:swap;src:url('./%s') format('woff2');unicode-range:%s}" % (family, weight, dest.name, ranges(points)))
        manifest.append({'file': dest.name, 'weight': weight, 'family': family, 'glyphs': len(points), 'bytes': dest.stat().st_size, 'sha256': hashlib.sha256(dest.read_bytes()).hexdigest(), 'unicodeRange': ranges(points)})
    print(stem, 'source characters', len(cmap), 'web characters', sum(len(x[1]) for x in groups), 'shards', len(groups), flush=True)
for name in ['source-serif-OFL.txt', 'mashanzheng-OFL.txt']:
    shutil.copy2(SOURCE / name, OUT / name)
(OUT / 'game-fonts.css').write_text('\n'.join(css) + '\n')
(OUT / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
